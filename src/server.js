app.get("/api/pdf/economy/:month", auth, async (req, res) => {
  const m = req.params.month;

  const r = await db.query(
    `SELECT * FROM transactions
     WHERE LEFT(tx_date,7)=$1
     ORDER BY tx_date DESC`,
    [m]
  );

  const rows = r.rows;

  const income = rows
    .filter(x => x.type === "income")
    .reduce((s, x) => s + Number(x.amount), 0);

  const expense = rows
    .filter(x => x.type === "expense")
    .reduce((s, x) => s + Number(x.amount), 0);

  const doc = new PDFDocument({ margin: 45 });

  res.setHeader("Content-Type", "application/pdf");
  res.setHeader(
    "Content-Disposition",
    `attachment; filename="beaumont-${m}-ekonomi.pdf"`
  );

  doc.pipe(res);

  doc.fontSize(22).text("BEAUMONT CLUB", {
    align: "center"
  });

  doc.moveDown(0.3);

  doc.fontSize(16).text(`Ekonomik Durum — ${m}`, {
    align: "center"
  });

  doc.moveDown();

  doc.fontSize(12).text(
    `Toplam Gelir: €${income.toFixed(2)}`
  );

  doc.text(
    `Toplam Gider: €${expense.toFixed(2)}`
  );

  doc.text(
    `Net: €${(income - expense).toFixed(2)}`
  );

  doc.moveDown();
  doc.fontSize(14).text("Hareketler");

  rows.forEach(t => {
    doc.fontSize(10).text(
      `${t.tx_date} | ${t.type === "income" ? "Gelir" : "Gider"} | ${t.category} | ${t.description || ""} | €${Number(t.amount).toFixed(2)}`
    );
  });

  doc.end();
});

