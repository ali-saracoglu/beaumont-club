app.get("/api/economy/:month", auth, async (req, res) => {
  const m = req.params.month;

  const r = await db.query(
    `SELECT * FROM transactions
     WHERE LEFT(tx_date,7)=$1
     ORDER BY tx_date DESC`,
    [m]
  );

  const rows = r.rows;

  const income = rows
    .filter(x => x.type === "income")
    .reduce((s, x) => s + Number(x.amount), 0);

  const expense = rows
    .filter(x => x.type === "expense")
    .reduce((s, x) => s + Number(x.amount), 0);

  res.json({
    month: m,
    income,
    expense,
    net: income - expense,
    rows
  });
});

